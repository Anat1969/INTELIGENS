"""Merge fusion card JSON batches into src/data/fusions.ts (run: python3 scripts/build-fusions.py a.json b.json ...)."""
import json, sys, itertools
IDS = ["linguistic","logical","spatial","musical","kinesthetic","interpersonal","intrapersonal","naturalist","existential","emotional","digital","systems"]
FIELDS = ["name","type","distillation","friction","transplant","definition","recognize","mind","heart","gut","intuition","practice","novelty","insight","visual","imagePrompt","roles"]
SUFFIX = "Documentary realism, Professional architecture photography, 1:1 --no text, words, writing, frame divisions"
data = {}
for path in sys.argv[1:]:
    data.update(json.load(open(path, encoding="utf-8")))
problems = []
for k, v in data.items():
    for f in FIELDS:
        if not v.get(f): problems.append(f"{k}: missing {f}")
    if not v.get("imagePrompt", "").strip().endswith(SUFFIX): problems.append(f"{k}: prompt suffix")
expected = {"+".join(sorted(p)) for p in itertools.combinations(IDS, 2)}
missing = sorted(expected - set(data))
names = [v["name"] for v in data.values()]
dups = sorted({n for n in names if names.count(n) > 1})
print(f"{len(data)} cards, missing {len(missing)}, problems {len(problems)}, duplicate names {dups}")
for p in problems[:20]: print(" ", p)
for m in missing: print("  missing", m)
ordered = {k: {f: data[k][f] for f in FIELDS} for k in sorted(data)}
out = ("// Generated by scripts/build-fusions.py from the curated fusion cards. Edit the cards, then regenerate.\n"
       "import type { Fusion } from '@/lib/fusion'\n\n"
       "export const FUSIONS: Record<string, Fusion> = " + json.dumps(ordered, ensure_ascii=False, indent=2) + "\n")
open("src/data/fusions.ts", "w", encoding="utf-8").write(out)
