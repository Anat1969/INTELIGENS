export function generateDynamic(ids: IntelligenceId[]): Combo {
  const len = ids.length;
  if (len >= 6) return PATTERN_POLYMATH;
  if (len >= 4) return PATTERN_MULTI_DIM;

  const hasLogic = ids.some((i) => ["logical", "systems", "digital"].includes(i));
  const hasPeople = ids.some((i) =>
    ["interpersonal", "emotional", "intrapersonal"].includes(i),
  );
  const hasCreative = ids.some((i) =>
    ["linguistic", "musical", "spatial"].includes(i),
  );
  if (hasLogic && hasPeople && hasCreative) return PATTERN_TRANSLATOR;
  return PATTERN_POLYMATH_3;
}

export function lookupCombo(ids: IntelligenceId[]): Combo {
  const key = [...ids].sort().join("+");
  return COMBOS[key] ?? generateDynamic(ids);
}
