function generateDynamicProfile(ids: IntelligenceId[]): Combo {
  const len = ids.length;
  if (len >= 6) return PERSONAL_PATTERN_POLYMATH;
  if (len >= 4) return PERSONAL_PATTERN_MULTI;

  const hasLogic = ids.some((i) => ["logical", "systems", "digital"].includes(i));
  const hasPeople = ids.some((i) =>
    ["interpersonal", "emotional", "intrapersonal"].includes(i),
  );
  const hasCreative = ids.some((i) =>
    ["linguistic", "musical", "spatial"].includes(i),
  );
  if (hasLogic && hasPeople && hasCreative) return PERSONAL_PATTERN_TRANSLATOR;
  return PERSONAL_PATTERN_BORDER;
}

export function lookupProfileCombo(ids: IntelligenceId[]): Combo {
  const key = [...ids].sort().join("+");
  return PROFILE_COMBOS[key] ?? generateDynamicProfile(ids);
}
